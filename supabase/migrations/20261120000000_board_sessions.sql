-- Board séances (Kilter, Tension, MoonBoard): a third kind of climbing séance,
-- next to gym bouldering and routes.
--
-- * sessions.discipline gains 'BOARD'; the séance keeps its board, layout and
--   the angle it was set at. Every existing séance is untouched.
-- * board_ascents records each climb: the name shown in the board app, the grade
--   exactly as entered (Font or V), the angle of that climb, tries and result.
--   Board grades are never mixed with gym colours or route grades.
-- * board_projects: a climb not sent yet, kept as a project. The same board,
--   name and angle make the same climb.
-- * One shared "home" venue, so a board at home needs no gym.
-- Purely additive: no existing row or column changes meaning.

alter table public.sessions drop constraint sessions_discipline_check;
alter table public.sessions add constraint sessions_discipline_check
  check (discipline in ('BOULDER', 'ROUTE', 'BOARD'));
alter table public.sessions
  add column board text check (board in ('KILTER', 'TENSION', 'MOON')),
  add column board_layout text check (board_layout is null or char_length(btrim(board_layout)) between 1 and 40),
  -- The angle the board is set at; each climb keeps its own.
  add column board_angle smallint check (board_angle is null or board_angle between 0 and 90);
alter table public.sessions add constraint sessions_board_only_on_board
  check ((discipline = 'BOARD') = (board is not null));
comment on column public.sessions.discipline is
  'BOULDER: attempts on problems. ROUTE: route_ascents in the French sport scale. BOARD: board_ascents on a training board. Never mixed.';

-- The venue for a board at home. external_provider keeps it out of the gym and outdoor lists.
insert into public.gyms (name, brand, country, grading_system, has_bouldering, has_routes, external_provider, external_id, created_by)
values ('À la maison', 'OTHER', 'FR', 'FONT', true, false, 'leblond-board', 'home', null)
on conflict (external_provider, external_id) do nothing;

create table public.board_ascents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  session_id uuid not null references public.sessions(id) on delete cascade,
  -- Generated by the client for each tap so a retried request never duplicates a climb.
  client_id uuid not null,
  -- Copy of the séance's board: a climb's history is read per board, across séances.
  board text not null check (board in ('KILTER', 'TENSION', 'MOON')),
  climb_name text not null check (char_length(btrim(climb_name)) between 1 and 120),
  -- Accent/case-insensitive key computed by the app (lib/climbing/boards.ts climbKey).
  climb_key text not null check (char_length(climb_key) between 1 and 120),
  angle smallint not null check (angle between 0 and 90),
  -- As entered, in the scale the climber reads in the board app. Never converted.
  grade text not null check (char_length(grade) between 1 and 8),
  grade_scale text not null check (grade_scale in ('FONT', 'V')),
  tries smallint not null default 1 check (tries between 1 and 999),
  -- FLASH: sent first go. SENT: sent after tries. ATTEMPT: not yet.
  result text not null check (result in ('FLASH', 'SENT', 'ATTEMPT')),
  is_benchmark boolean not null default false,
  is_mirror boolean not null default false,
  notes text not null default '' check (char_length(notes) <= 500),
  climbed_at timestamptz not null default now(),
  -- BOARDLIB: imported from a BoardLib logbook file the climber exported themself.
  source text not null default 'MANUAL' check (source in ('MANUAL', 'BOARDLIB')),
  -- Stable reference of an imported line, so importing the same file twice adds nothing.
  external_ref text check (external_ref is null or char_length(external_ref) between 1 and 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, client_id),
  constraint board_ascents_flash_is_one_try check (result <> 'FLASH' or tries = 1)
);
create index board_ascents_session on public.board_ascents (session_id, climbed_at);
create index board_ascents_climb on public.board_ascents (user_id, board, climb_key, angle);
create unique index board_ascents_external on public.board_ascents (user_id, external_ref) where external_ref is not null;
create trigger board_ascents_updated_at before update on public.board_ascents
  for each row execute function public.set_updated_at();

alter table public.board_ascents enable row level security;
-- Supabase default privileges grant ALL; start from nothing.
revoke all on public.board_ascents from anon, authenticated;
grant select, insert, delete on public.board_ascents to authenticated;
grant update (climb_name, climb_key, angle, grade, grade_scale, tries, result, is_benchmark, is_mirror, notes)
  on public.board_ascents to authenticated;

create policy board_ascents_select on public.board_ascents for select to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());
create policy board_ascents_insert on public.board_ascents for insert to authenticated
  with check (user_id = auth.uid() and public.is_active_beta_user()
    and exists (select 1 from public.sessions s
      where s.id = session_id and s.user_id = auth.uid() and s.discipline = 'BOARD' and s.board = board_ascents.board));
create policy board_ascents_update on public.board_ascents for update to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user())
  with check (user_id = auth.uid() and public.is_active_beta_user());
create policy board_ascents_delete on public.board_ascents for delete to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());

create table public.board_projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  board text not null check (board in ('KILTER', 'TENSION', 'MOON')),
  climb_name text not null check (char_length(btrim(climb_name)) between 1 and 120),
  climb_key text not null check (char_length(climb_key) between 1 and 120),
  angle smallint not null check (angle between 0 and 90),
  grade text not null check (char_length(grade) between 1 and 8),
  grade_scale text not null check (grade_scale in ('FONT', 'V')),
  status text not null default 'ACTIVE' check (status in ('ACTIVE', 'SENT', 'ABANDONED')),
  notes text not null default '' check (char_length(notes) <= 2000),
  started_at timestamptz not null default now(),
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- The same board, name and angle make the same climb.
  unique (user_id, board, climb_key, angle),
  constraint board_projects_sent_has_date check (status <> 'SENT' or sent_at is not null)
);
create index board_projects_owner on public.board_projects (user_id, status, started_at desc);
create trigger board_projects_updated_at before update on public.board_projects
  for each row execute function public.set_updated_at();

alter table public.board_projects enable row level security;
revoke all on public.board_projects from anon, authenticated;
grant select, insert, delete on public.board_projects to authenticated;
grant update (grade, grade_scale, status, notes, sent_at) on public.board_projects to authenticated;

create policy board_projects_select on public.board_projects for select to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());
create policy board_projects_insert on public.board_projects for insert to authenticated
  with check (user_id = auth.uid() and public.is_active_beta_user());
create policy board_projects_update on public.board_projects for update to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user())
  with check (user_id = auth.uid() and public.is_active_beta_user());
create policy board_projects_delete on public.board_projects for delete to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());
