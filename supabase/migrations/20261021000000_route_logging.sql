-- Route (sport / roped) climbing log, kept separate from bouldering.
--
-- * sessions.discipline tells the two apart. Every existing session is a
--   bouldering session, so the default keeps all history and analytics intact.
-- * route_ascents records each climb of a route in the French sport scale.
--   It never reuses boulder problems, colour circuits or Font grades, and no
--   conversion between the two scales is ever made.
-- Purely additive: no existing row or column changes meaning.

alter table public.sessions
  add column discipline text not null default 'BOULDER'
  check (discipline in ('BOULDER','ROUTE'));
comment on column public.sessions.discipline is
  'BOULDER: attempts on problems. ROUTE: route_ascents in the French sport scale. Never mixed.';

create table public.route_ascents (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  session_id uuid not null references public.sessions(id) on delete cascade,
  -- Generated by the client for each tap so a retried request never duplicates an ascent.
  client_id uuid not null,
  route_name text check (route_name is null or char_length(btrim(route_name)) between 1 and 120),
  grade text not null check (grade = any (array[
    '3a','3b','3c','4a','4b','4c',
    '5a','5a+','5b','5b+','5c','5c+',
    '6a','6a+','6b','6b+','6c','6c+',
    '7a','7a+','7b','7b+','7c','7c+',
    '8a','8a+','8b','8b+','8c','8c+',
    '9a','9a+','9b','9b+','9c'])),
  style text not null check (style in ('LEAD','TOPROPE','AUTOBELAY')),
  -- ONSIGHT / FLASH / REDPOINT are clean ascents (no fall, no rest on the rope).
  -- TOP_WITH_REST reached the top after falls or takes. ATTEMPT did not reach the top.
  result text not null check (result in ('ONSIGHT','FLASH','REDPOINT','TOP_WITH_REST','ATTEMPT')),
  falls smallint check (falls is null or falls between 0 and 50),
  wall_angle public.wall_angle not null default 'UNKNOWN',
  notes text not null default '' check (char_length(notes) <= 500),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, client_id),
  constraint route_ascents_clean_has_no_falls check (result not in ('ONSIGHT','FLASH','REDPOINT') or coalesce(falls, 0) = 0)
);
create index route_ascents_session on public.route_ascents (session_id, created_at);
create index route_ascents_owner on public.route_ascents (user_id, created_at desc);
create trigger route_ascents_updated_at before update on public.route_ascents
  for each row execute function public.set_updated_at();

alter table public.route_ascents enable row level security;
-- Supabase default privileges grant ALL; start from nothing.
revoke all on public.route_ascents from anon, authenticated;
grant select, insert, delete on public.route_ascents to authenticated;
grant update (route_name, grade, style, result, falls, wall_angle, notes) on public.route_ascents to authenticated;

create policy route_ascents_select on public.route_ascents for select to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());
create policy route_ascents_insert on public.route_ascents for insert to authenticated
  with check (user_id = auth.uid() and public.is_active_beta_user()
    and exists (select 1 from public.sessions s
      where s.id = session_id and s.user_id = auth.uid() and s.discipline = 'ROUTE'));
create policy route_ascents_update on public.route_ascents for update to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user())
  with check (user_id = auth.uid() and public.is_active_beta_user());
create policy route_ascents_delete on public.route_ascents for delete to authenticated
  using (user_id = auth.uid() and public.is_active_beta_user());
